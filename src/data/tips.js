let _lastIdx = -1;
// 연속 같은 팁이 안 나오게
export function randomTip() {
  let idx;
  do {
    idx = Math.floor(Math.random() * TIPS.length);
  } while (idx === _lastIdx && TIPS.length > 1);
  _lastIdx = idx;
  return TIPS[idx];
}
